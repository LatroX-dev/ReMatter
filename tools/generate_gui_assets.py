def palette():
    colors = {name: tuple(bytes.fromhex(value)[index] for index in (1, 2, 3, 0))
              for name, value in re.findall(r"\bint\s+(\w+)\s*=\s*0x([0-9a-fA-F]{8})", PALETTE.read_text())}
    required = {"BACKGROUND", "PANEL", "SURFACE", "SURFACE_ACTIVE", "BORDER", "HIGHLIGHT", "RECESS",
                "ACCENT", "ACCENT_BRIGHT", "MUTED", "TEXT", "SLOT_EDGE"}
    if not required.issubset(colors):
        raise ValueError("Missing GUI palette roles: " + ", ".join(sorted(required - colors.keys())))
    # The one-pixel edge lights and shadows of the existing graphite controls.
    colors["FRAME_LIGHT"] = (100, 114, 126, 255)
    colors["FRAME_SHADE"] = (10, 13, 17, 255)
    return colors


class Canvas:
    def __init__(self, width, color, height=None):
        self.width, self.height = width, width if height is None else height
        self.size = width
        self.rows = [[color] * self.width for _ in range(self.height)]

    def rect(self, left, top, right, bottom, color):
        if not (0 <= left <= right <= self.width and 0 <= top <= bottom <= self.height):
            raise ValueError("GUI frame leaves its sprite")
        for y in range(top, bottom):
            for x in range(left, right):
                self.rows[y][x] = color

    def pixel(self, x, y):
        return self.rows[y][x]


def panel(colors):
    image = Canvas(16, colors["FRAME_SHADE"])
    image.rect(1, 1, 15, 15, colors["BACKGROUND"])
    image.rect(1, 1, 15, 2, colors["FRAME_LIGHT"])
    image.rect(1, 2, 2, 14, colors["BORDER"])
    image.rect(2, 2, 14, 3, colors["HIGHLIGHT"])
    image.rect(14, 2, 15, 15, colors["RECESS"])
    image.rect(2, 14, 15, 15, colors["RECESS"])
    return image


def button(colors, hover=False, enabled=True):
    image = Canvas(16, colors["FRAME_SHADE"])
    image.rect(0, 0, 15, 15, colors["FRAME_LIGHT"] if hover and enabled else colors["BORDER"])
    image.rect(1, 1, 14, 14, colors["SURFACE_ACTIVE"] if hover and enabled
               else colors["SURFACE"] if enabled else colors["PANEL"])
    image.rect(1, 1, 14, 2, colors["FRAME_LIGHT"] if hover and enabled
               else colors["FRAME_LIGHT"] if enabled else colors["HIGHLIGHT"])
    image.rect(1, 2, 2, 14, colors["HIGHLIGHT"] if enabled else colors["PANEL"])
    image.rect(2, 13, 14, 14, colors["RECESS"])
    return image


def inset(colors, size=16, slot=False):
    image = Canvas(size, colors["HIGHLIGHT"])
    image.rect(0, 0, size - 1, size - 1, colors["FRAME_SHADE"])
    image.rect(1, 1, size - 1, size - 1, colors["RECESS"])
    if slot:
        image.rect(0, 0, size, 1, colors["SLOT_EDGE"])
    return image


def scroll_thumb(colors, active=False):
    """A raised bar that a scrollbar stretches along its track."""
    image = Canvas(4, colors["ACCENT" if active else "BORDER"], 8)
    image.rect(0, 0, 4, 1, colors["ACCENT_BRIGHT" if active else "MUTED"])
    image.rect(0, 7, 4, 8, colors["FRAME_SHADE"])
    return image


def progress_arrow():
    """The white process arrow. A screen draws it once as the track and once, clipped, as the filled part."""
    image = Canvas(24, MONO["."], 16)
    for x in range(24):
        half = 3 if x < 16 else 23 - x
        image.rect(x, 7 - half, x + 1, 8 + half, MONO["#"])
    return image


def scaling(width, height, border):
    # Minecraft's GUI sprite metadata keeps these border pixels fixed when blitSprite resizes the frame.
    if border * 2 >= min(width, height):
        raise ValueError("A nine-slice frame needs a nonempty centre")
    return {"gui": {"scaling": {"type": "nine_slice", "width": width, "height": height, "border": border}}}


