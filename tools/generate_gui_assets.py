#!/usr/bin/env python3
"""Generate the graphite GUI frames and the pixel icon set of the ReMatter screens.

Frames (panel, buttons, inset, slot, scroll thumb) take their colours from UiPalette.java and carry
nine-slice metadata. Icons are 16 x 16 sprites under textures/gui/sprites/icon/ and are referenced as
rematter:icon/<name>.

Icon rules, checked on every run:
  * One ink. A mono icon holds white ink ('#') and at most one softer tone (':', the same white at
    TONE_ALPHA), so the screen tints the whole icon with one colour per draw call.
  * Control icons live in a 12 x 12 block centred on the canvas, so they fit a 16 px button. Tab
    icons and slot ghosts may use a 14 x 14 block.
  * Silhouettes are solid or 2 px strokes; 1 px lines are for detail. An icon must read without tone.
  * Only the status lamps are colour sprites. Their hue is a status LED of family_palette.py and
    their mark is the dark recess colour, so they are drawn untinted and mean status only.

RESEARCH_ICON selects which of the three Research candidates is written as icon/research. RESERVE
lists drawings that are kept here but not written, because no screen draws them yet.
"""
