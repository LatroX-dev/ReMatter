def lamp_colors(colors):
    return {**MONO, "G": LED["green"] + (255,), "B": LED["blue"] + (255,), "A": LED["amber"] + (255,),
            "R": LED["red"] + (255,), "K": colors["RECESS"], "W": colors["TEXT"]}


def parse_icons(text=ICON_ART):
    """Return {name: (group, rows)} after checking the size and vocabulary of every drawing."""
    icons, name = {}, None
    for line in text.strip().splitlines():
        line = line.strip()
        if not line:
            continue
        if line.startswith("="):
            _, name, group = line.split()
            if not re.fullmatch(r"[a-z][a-z0-9_]*", name) or name in icons:
                raise ValueError(f"Invalid or repeated icon name: {name}")
            icons[name] = (group, [])
        else:
            icons[name][1].append(line)
    drawings = {}
    for name, (group, rows) in icons.items():
        block = 14 if group in WIDE_GROUPS else 12
        if len(rows) != block or any(len(row) != block for row in rows):
            raise ValueError(f"Icon {name} must be a {block} x {block} block")
        allowed = set("#:.GBARKW") if group == "lamp" else set("#:.")
        if not set("".join(rows)) <= allowed:
            raise ValueError(f"Icon {name} uses a colour outside its group")
        solid = [(x, y) for y, row in enumerate(rows) for x, value in enumerate(row) if value not in ".:"]
        if len(solid) < 16:
            raise ValueError(f"Icon {name} has too little ink to read at 1x")
        width = max(x for x, _ in solid) - min(x for x, _ in solid) + 1
        height = max(y for _, y in solid) - min(y for _, y in solid) + 1
        if max(width, height) < 10:
            raise ValueError(f"Icon {name} is smaller than the 12 px glyph box allows")
        key = tuple(rows)
        if key in drawings:
            raise ValueError(f"Icons {name} and {drawings[key]} are the same drawing")
        drawings[key] = name
    for candidate in (*RESEARCH_CANDIDATES, RESEARCH_ICON):
        if candidate not in icons or candidate not in RESEARCH_CANDIDATES:
            raise ValueError(f"Unknown Research icon candidate: {candidate}")
    if "research" in icons:
        raise ValueError("icon/research is written from RESEARCH_ICON")
    if not set(RESERVE) <= icons.keys() - set(RESEARCH_CANDIDATES):
        raise ValueError("RESERVE names a drawing that does not exist")
    return icons


def icon_image(group, rows, colors):
    """The 16 x 16 sprite of one drawing, centred on the canvas."""
    table = lamp_colors(colors) if group == "lamp" else MONO
    image = Canvas(CANVAS, MONO["."])
    offset = (CANVAS - len(rows)) // 2
    for y, row in enumerate(rows):
        for x, value in enumerate(row):
            image.rows[offset + y][offset + x] = table[value]
    return image


def icon_images(colors, shipped_only=True):
    """Icon sprites by name. The shipped set holds icon/research instead of the three candidates
    and leaves out RESERVE; a review sheet asks for every drawing."""
    drawn = {name: icon_image(group, rows, colors) for name, (group, rows) in parse_icons().items()}
    if not shipped_only:
        return drawn
    images = {name: image for name, image in drawn.items() if name not in (*RESEARCH_CANDIDATES, *RESERVE)}
    images["research"] = drawn[RESEARCH_ICON]
    return images


def frame_images(colors):
    """Stretched frames by name with their nine-slice border."""
    return {
        "panel": (panel(colors), 3),
        "button": (button(colors), 3),
        "button_hover": (button(colors, hover=True), 3),
        "button_disabled": (button(colors, enabled=False), 3),
        "inset": (inset(colors), 1),
        "slot": (inset(colors, size=18, slot=True), 1),
        "scroll_thumb": (scroll_thumb(colors), 1),
        "scroll_thumb_active": (scroll_thumb(colors, active=True), 1),
    }


def generate(check):
    colors = palette()
    frames, icons = frame_images(colors), icon_images(colors)
    out = GeneratedFiles(ROOT, check)
    for name, (image, border) in frames.items():
        out.png(SPRITES / (name + ".png"), image.width, image.height, image.pixel)
        out.json(SPRITES / (name + ".png.mcmeta"), scaling(image.width, image.height, border))
    arrow = progress_arrow()
    out.png(SPRITES / "progress_arrow.png", arrow.width, arrow.height, arrow.pixel)
    for name, image in icons.items():
        out.png(ICONS / (name + ".png"), CANVAS, CANVAS, image.pixel)
    # The icon folder belongs to this generator: a renamed or removed icon must not stay behind.
    stale = sorted(path for path in ICONS.glob("*") if path.stem not in icons or path.suffix != ".png")
    if stale and check:
        raise ValueError("Icon files without a drawing: " + ", ".join(path.name for path in stale))
    for path in stale:
        path.unlink()
    print(("Verified" if check else "Generated")
          + f" {out.count} GUI sprite files ({len(frames)} frames, 1 progress arrow, {len(icons)} icons)")


def listing():
    for name, (group, _) in parse_icons().items():
        kind = "colour" if group == "lamp" else "tinted"
        if name in RESEARCH_CANDIDATES:
            state = "written as icon/research" if name == RESEARCH_ICON else "candidate, not written"
        else:
            state = "reserve, not written" if name in RESERVE else f"icon/{name}"
        print(f"{name}\t{group}\t{kind}\t{state}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="compare generated sprites without changing files")
    parser.add_argument("--list", action="store_true", help="print every icon id with its group and exit")
    arguments = parser.parse_args()
    if arguments.list:
        listing()
    else:
        generate(arguments.check)
